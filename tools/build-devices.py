#!/usr/bin/env python3
"""Merge researched screen specs (JSON arrays) into devices.js.

Usage: tools/build-devices.py research/*.json > devices.js
Each input entry: brand, name, screen, uaModels, res [short,long], ppi,
ppiPublishedBy, diag, diagMm, src.
"""
import json, re, sys

BRAND_ORDER = ['Google', 'Samsung', 'Apple']

def natkey(s):
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r'(\d+)', s)]

rows, skipped = [], []
for path in sys.argv[1:]:
    for e in json.load(open(path)):
        res = e.get('res')
        if not res or not all(res) or not (e.get('ppi') or e.get('diag') or e.get('diagMm')):
            skipped.append(f"{e.get('brand')} {e.get('name')} ({e.get('screen')})")
            continue
        r = sorted(int(x) for x in res)
        row = {'b': e['brand'], 'n': e['name'], 's': e.get('screen') or 'main', 'ua': e.get('uaModels') or [], 'r': r}
        if e.get('ppi'):
            row['ppi'] = e['ppi']
            row['by'] = 'm' if e.get('ppiPublishedBy') == 'manufacturer' else 's'
        if e.get('diag'): row['d'] = e['diag']
        if e.get('diagMm'): row['dmm'] = e['diagMm']
        if e.get('src'): row['src'] = e['src'][0]
        rows.append(row)

rank = lambda b: BRAND_ORDER.index(b) if b in BRAND_ORDER else len(BRAND_ORDER)
rows.sort(key=lambda d: (rank(d['b']), d['b']))
# newest first within a brand (natural sort, descending), main screen before cover
out, i = [], 0
from itertools import groupby
for _, grp in groupby(rows, key=lambda d: d['b']):
    g = sorted(grp, key=lambda d: (natkey(d['n']), d['s'] != 'main'), reverse=True)
    out.extend(sorted(g, key=lambda d: natkey(d['n']), reverse=True))

print('// Screen specs from manufacturer spec pages (by:"m") or secondary sources (by:"s").')
print('// Generated by tools/build-devices.py from research/*.json. Fields: b brand, n name, s screen,')
print('// ua model strings Chrome reports, r native resolution [short,long], ppi, d diagonal in, dmm diagonal mm, src source.')
print('window.DEVICES = [')
for d in out:
    print('  ' + json.dumps(d, ensure_ascii=False, separators=(',', ':')) + ',')
print('];')
if skipped:
    print(f'skipped {len(skipped)} incomplete: ' + '; '.join(skipped), file=sys.stderr)
print(f'{len(out)} screens', file=sys.stderr)
